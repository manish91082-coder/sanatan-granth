"""तुलना-कुंजी (मास्टर योजना §3.1 "दो परतें")।

प्रदर्शन-पाठ "जैसा छपा है" रहता है; गवाहों का मिलान इस normalised कुंजी पर होता है। कुंजी केवल
लिखावट के वे अंतर मिटाती है जो पाठ नहीं बदलते:
  NFC · ZWJ/ZWNJ · दण्ड/अंक/विराम · वैदिक स्वर-चिह्न · अवग्रह · ॐ के रूप ·
  अनुस्वार/चन्द्रबिन्दु/वैदिक अनुस्वार और स्पर्श से पहले का वर्गीय नासिक्य → एक placeholder (N) ·
  पदच्छेद की खाली जगह (हलन्त + स्वतंत्र स्वर → मात्रा)।
कुंजी बराबर = "लिखावट छोड़कर वही पाठ"। कुंजी अलग = वर्तनी से बड़ा अंतर; उसे इंसान/अगला क़दम वर्गीकृत करे।
यह कुंजी कभी प्रदर्शित या संग्रहीत पाठ नहीं बनती।
"""
from __future__ import annotations

import hashlib
import re
import unicodedata

_VOWEL_TO_MATRA = {"अ": "", "आ": "ा", "इ": "ि", "ई": "ी", "उ": "ु", "ऊ": "ू", "ऋ": "ृ", "ॠ": "ॄ", "ए": "े", "ऐ": "ै", "ओ": "ो", "औ": "ौ"}
_STOP = "क-म"  # क…म: पाँचों वर्ग


def key(s: str) -> str:
    s = unicodedata.normalize("NFC", s)
    s = re.sub(r"ओ\s*[3३]\s*म्|ओम्|ॐ", "ॐ", s)
    s = re.sub(r"(?<=[ऀ-ॿ]):", "ः", s)  # ASCII ':' विसर्ग की जगह
    # वैदिक अनुस्वार के रूप → अनुस्वार (स्वर-चिह्न हटाने से पहले)
    s = re.sub(r"[ꣲ-ꣷᳩ-ᳱ]", "ं", s)
    s = re.sub(r"[॑-॔᳐-᳨ᳲ-᳿꣠-꣱]", "", s)  # स्वर-चिह्न
    s = s.replace("‌", "").replace("‍", "").replace("ऽ", "")
    s = re.sub(r"[।॥०-९0-9.,;!?'\"()\[\]{}<>|/\\*_=+~`^-]", " ", s)
    s = re.sub(r"\s+", " ", s).strip()
    # पदच्छेद: हलन्त + खाली जगह + स्वतंत्र स्वर → मात्रा
    s = re.sub(r"्\s+([अआइईउऊऋॠएऐओऔ])", lambda m: _VOWEL_TO_MATRA[m.group(1)], s)
    s = s.replace(" ", "")
    s = re.sub(r"[ंँ]+", "N", s)
    s = re.sub(rf"[ङञणनम]्(?=[{_STOP}])", "N", s)
    s = re.sub(r"N+", "N", s)
    return s


def key_hash(s: str) -> str:
    return hashlib.sha256(key(s).encode("utf-8")).hexdigest()
